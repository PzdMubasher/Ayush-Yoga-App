  // Gracefully translate dynamic texts (case-insensitive/normalized match)
  String translateDynamic(String text) {
    if (_currentLanguage == 'en') return text;
    
    final normalized = text.trim().toLowerCase().replaceAll(RegExp(r'\s+'), ' ');
    
    // Choose the right dynamic map based on language
    final Map<String, String> dynamicMap = _currentLanguage == 'te'
        ? _teDynamicTranslationsLower
        : _hiDynamicTranslationsLower;
    
    // 1. Exact dynamic map lookup
    if (dynamicMap.containsKey(normalized)) {
      return dynamicMap[normalized]!;
    }
    
    // 2. Safely translate clauses split by punctuation (e.g. "Sit upright, and close your eyes")
    final punctuationRegex = RegExp(r'([,.;!]+)');
    final parts = text.split(punctuationRegex);
    final separators = punctuationRegex.allMatches(text).map((m) => m.group(0)!).toList();
    
    List<String> translatedParts = [];
    bool anyTranslated = false;
    
    for (int i = 0; i < parts.length; i++) {
      final part = parts[i];
      final partNorm = part.trim().toLowerCase().replaceAll(RegExp(r'\s+'), ' ');
      
      if (partNorm.isEmpty) {
        translatedParts.add(part);
        continue;
      }
      
      // Look for exact match for the clause
      if (dynamicMap.containsKey(partNorm)) {
        translatedParts.add(dynamicMap[partNorm]!);
        anyTranslated = true;
      } else {
        // If no exact match for clause, match whole English phrases with word boundaries
        String processedPart = partNorm;
        final sortedKeys = dynamicMap.keys.toList()
          ..sort((a, b) => b.length.compareTo(a.length));
          
        for (var key in sortedKeys) {
          final keyEscaped = RegExp.escape(key);
          final reg = RegExp('\\b$keyEscaped\\b');
          if (reg.hasMatch(processedPart)) {
            processedPart = processedPart.replaceAll(reg, dynamicMap[key]!);
            anyTranslated = true;
          }
        }
        
        // If we replaced something, use it; otherwise fallback to original part text
        if (processedPart != partNorm) {
          translatedParts.add(processedPart);
        } else {
          translatedParts.add(part);
        }
      }
    }
    
    if (anyTranslated) {
      StringBuffer sb = StringBuffer();
      for (int i = 0; i < translatedParts.length; i++) {
        sb.write(translatedParts[i]);
        if (i < separators.length) {
          sb.write(separators[i]);
          sb.write(" "); // Space after punctuation for readability
        }
      }
      return sb.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
    }
    
    return text;
  }
